/**
 * Returns a randomized sentence for a specific stage from its difficulty bucket
 */
export function getRandomSentenceForStage(stageIndex: number): string {
  const safeIdx = Math.max(0, Math.min(stageIndex, STAGE_SENTENCE_BUCKETS.length - 1));
  const bucket = STAGE_SENTENCE_BUCKETS[safeIdx];
  if (!bucket || bucket.length === 0) return ALL_SENTENCES[0];
  const randIdx = Math.floor(Math.random() * bucket.length);
  return bucket[randIdx];
}

