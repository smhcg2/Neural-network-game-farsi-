// Helper to select a fresh question from the 20-question pool
export function getQuizForCheckpoint(answeredQuizIds: string[] = []): QuizQuestion {
  const available = EDUCATIONAL_QUIZ_POOL.filter((q) => !answeredQuizIds.includes(q.id));
  const pool = available.length > 0 ? available : EDUCATIONAL_QUIZ_POOL;
  const randIdx = Math.floor(Math.random() * pool.length);
  return pool[randIdx];
}

